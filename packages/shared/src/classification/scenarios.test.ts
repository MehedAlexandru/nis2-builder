function answersFor(row: ScenarioRow): ClassificationAnswers {
  return classificationAnswersSchema.parse({
    establishmentCountries: ['RO'],
    sectorCode: row.sector,
    subsectorCode: row.subsector,
    entityTypeCode: row.entity,
    size: {
      employees: row.employees,
      annualTurnoverEur: row.turnover,
      balanceSheetTotalEur: row.balance,
      consolidation:
        row.name.includes('linked') || row.name.includes('partner')
          ? 'PARTNER_LINKED'
          : 'AUTONOMOUS',
      linkedEnterprises: row.name.includes('linked')
        ? [
            {
              name: 'Linked large enterprise',
              employees: 300,
              annualTurnoverEur: 60_000_000,
              balanceSheetTotalEur: 50_000_000,
            },
          ]
        : [],
      partners: row.name.includes('partner')
        ? [
            {
              name: 'Partner enterprise',
              employees: 200,
              annualTurnoverEur: 40_000_000,
              balanceSheetTotalEur: 20_000_000,
              ownershipPercent: 50,
            },
          ]
        : [],
    },
    sizeIndependent: row.flags ?? {},
  });
}

describe('NIS2 classification scenario table', () => {
  it('contains at least 40 real-world scenarios', () => {
    expect(rows.length).toBeGreaterThanOrEqual(40);
  });

  for (const row of rows) {
    it(row.name, () => {
      const result = classify(pack, answersFor(row));
      expect(result.outcome).toBe(row.expected);
      expect(result.ruleId).toBe(row.expectedRule);
      expect(result.legalBasis.length).toBeGreaterThan(0);
      expect(result.legalBasis.every((entry) => entry.citation.length > 0)).toBe(true);
      expect(result.consequences.citations.length).toBeGreaterThan(0);
      expect(result.documents.length).toBeGreaterThan(0);
    });
  }
});

describe('classification pack invariants', () => {
  it('has a valid, non-draft RO pack with a citation on every rule', () => {
    expect(pack.code).toBe('RO');
    expect(pack.status).not.toBe('draft');
    expect(pack.rules.length).toBeGreaterThanOrEqual(10);
    for (const rule of pack.rules) {
      expect(rule.legalBasis.length).toBeGreaterThan(0);
      expect(rule.legalBasis.every((entry) => entry.citation.trim().length > 0)).toBe(true);
    }
  });

  it('has consequences for every possible outcome', () => {
    for (const outcome of ['ESSENTIAL', 'IMPORTANT', 'LIKELY_IN_SCOPE', 'OUT_OF_SCOPE'] as const) {
      const consequence = pack.consequences[outcome];
      if (!consequence) throw new Error(`Missing consequences for ${outcome}`);
      expect(consequence.heading.en.length).toBeGreaterThan(0);
      expect(consequence.citations.length).toBeGreaterThan(0);
    }
  });

  it('exposes the special not-listed selection without a catalog entry', () => {
    const selection = resolveSelection(
      pack,
      classificationAnswersSchema.parse({
        establishmentCountries: ['RO'],
        sectorCode: NOT_LISTED_SECTOR_CODE,
        subsectorCode: NOT_LISTED_SECTOR_CODE,
        entityTypeCode: NOT_LISTED_SECTOR_CODE,
        size: { employees: 1, annualTurnoverEur: 0, balanceSheetTotalEur: 0 },
      }),
    );
    expect(selection.annex).toBeNull();
    expect(selection.sectorName.en).toContain('Not listed');
  });
});
